#!/usr/bin/env python3
"""Write Local.xcconfig so a Debug build comes pre-paired with your TV, and optionally wired to
Home Assistant for power. Nothing secret is printed. Usage:

    scripts/seed.py --host 192.168.1.50 [--token-file tv_token.txt]
        [--ha-config ha.json --ha-entity media_player.living_room_tv]

The token file holds a pairing token the TV issued to the client name "Clicker". ha.json holds
{"ha_url": "...", "ha_token": "..."}. Builds made with --ha-config contain that token: keep them to yourself.
"""
import argparse, json, os, sys, urllib.request

ap = argparse.ArgumentParser()
ap.add_argument('--host', required=True, help="the TV's current IP address (it must be on or in standby)")
ap.add_argument('--token-file', help='file holding a pairing token for the client name "Clicker"')
ap.add_argument('--ha-config', help='JSON file with ha_url and ha_token')
ap.add_argument('--ha-entity', help='Home Assistant entity that turns the TV on, e.g. media_player.living_room_tv')
ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'Local.xcconfig'))
a = ap.parse_args()

info = json.load(urllib.request.urlopen(f'http://{a.host}:8001/api/v2/', timeout=4))
dev = info['device']
name = (dev.get('name') or 'Samsung TV').replace('&quot;', '"').replace('&amp;', '&').replace('&#39;', "'")
values = {
    'CLICKER_SEED_HOST': dev.get('ip') or a.host,
    'CLICKER_SEED_NAME': name,
    'CLICKER_SEED_MODEL': dev.get('modelName', ''),
    'CLICKER_SEED_ID': dev.get('id') or info.get('id') or a.host,
    'CLICKER_SEED_MAC': dev.get('wifiMac', ''),
    'CLICKER_SEED_TOKEN': open(a.token_file).read().strip() if a.token_file and os.path.exists(a.token_file) else '',
    'CLICKER_SEED_HA_URL': '', 'CLICKER_SEED_HA_ENTITY': '', 'CLICKER_SEED_HA_TOKEN': '',
}
if a.ha_config and a.ha_entity:
    ha = json.load(open(os.path.expanduser(a.ha_config)))
    values['CLICKER_SEED_HA_URL'] = ha['ha_url']
    values['CLICKER_SEED_HA_ENTITY'] = a.ha_entity
    values['CLICKER_SEED_HA_TOKEN'] = ha['ha_token']
for k, v in values.items():
    assert '\n' not in v, f'{k} has a newline, which xcconfig cannot hold'
# xcconfig starts a comment at //, which would cut http://host to http: ; $() expands to nothing.
escape = lambda v: v.replace('//', '/$()/')
with open(a.out, 'w') as f:
    f.write('// Generated by scripts/seed.py. Git-ignored. Debug builds only.\n')
    f.write('// Builds made with --ha-config carry the Home Assistant token: do not share them.\n')
    for k, v in values.items():
        f.write(f'{k} = {escape(v)}\n')
os.chmod(a.out, 0o600)
print('wrote', a.out, 'for', name, dev.get('modelName'), 'at', values['CLICKER_SEED_HOST'],
      '| tv token:', 'yes' if values['CLICKER_SEED_TOKEN'] else 'no', '| HA:', 'yes' if values['CLICKER_SEED_HA_TOKEN'] else 'no')
